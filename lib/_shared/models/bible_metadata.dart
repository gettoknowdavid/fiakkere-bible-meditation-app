  /// Book name from index. Returns empty string if index is out of range.
  static String bookName(int bookId) => books[bookId] ?? '';

  /// Book index from name. Returns -1 if not found.
  static int bookId(String name) => bookIndex[name] ?? -1;

  /// Number of chapters in a book.
  static int chapterCount(int bookId) => chapterCounts[bookId] ?? 0;

  /// Number of verses in a specific chapter (1-based chapter number).
  /// Returns 0 if book or chapter is out of range.
  static int verseCount(int bookId, int chapter) {
    final chapters = verseCounts[bookId];
    if (chapters == null || chapter < 1 || chapter > chapters.length) return 0;
    return chapters[chapter - 1];
  }

